/**
 * Pattern Nonogram riconoscibili (pixel art).
 * 1 = casella piena, 0 = vuota. Dimensioni: 5 (easy), 8 (medium), 10 (hard).
 */

function rows(lines: string[]): boolean[][] {
  return lines.map((line) => [...line].map((ch) => ch === '1' || ch === '#' || ch === 'X'))
}

